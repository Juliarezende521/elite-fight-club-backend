CREATE TABLE IF NOT EXISTS eventos_graduacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id BIGINT NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    descricao VARCHAR(2000),
    data_evento DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fim TIME NOT NULL,
    local_evento VARCHAR(200) NOT NULL,
    inicio_inscricoes TIMESTAMP NOT NULL,
    fim_inscricoes TIMESTAMP NOT NULL,
    status VARCHAR(40) NOT NULL,
    limite_participantes INTEGER,
    criado_em TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP NOT NULL,
    criado_por_id BIGINT NOT NULL,
    CONSTRAINT fk_eventos_graduacao_academia FOREIGN KEY (academia_id) REFERENCES academias(id),
    CONSTRAINT fk_eventos_graduacao_usuario FOREIGN KEY (criado_por_id) REFERENCES usuarios(id)
);

CREATE INDEX IF NOT EXISTS idx_eventos_graduacao_academia ON eventos_graduacao (academia_id);
CREATE INDEX IF NOT EXISTS idx_eventos_graduacao_status ON eventos_graduacao (academia_id, status);

CREATE TABLE IF NOT EXISTS eventos_graduacao_prajieds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL,
    graduacao_destino_id BIGINT NOT NULL,
    valor NUMERIC(10, 2) NOT NULL,
    limite_vagas INTEGER,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_eventos_prajieds_evento FOREIGN KEY (evento_id) REFERENCES eventos_graduacao(id),
    CONSTRAINT fk_eventos_prajieds_graduacao FOREIGN KEY (graduacao_destino_id) REFERENCES graduacoes(id),
    CONSTRAINT uk_evento_graduacao_prajied UNIQUE (evento_id, graduacao_destino_id)
);

CREATE INDEX IF NOT EXISTS idx_eventos_prajieds_evento ON eventos_graduacao_prajieds (evento_id);

CREATE TABLE IF NOT EXISTS convites_graduacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id BIGINT NOT NULL,
    evento_id BIGINT NOT NULL,
    aluno_id BIGINT NOT NULL,
    graduacao_atual_id BIGINT NOT NULL,
    graduacao_destino_id BIGINT NOT NULL,
    status VARCHAR(40) NOT NULL,
    enviado_em TIMESTAMP NOT NULL,
    visualizado_em TIMESTAMP,
    respondido_em TIMESTAMP,
    enviado_por_id BIGINT NOT NULL,
    justificativa VARCHAR(500),
    CONSTRAINT fk_convites_graduacao_academia FOREIGN KEY (academia_id) REFERENCES academias(id),
    CONSTRAINT fk_convites_graduacao_evento FOREIGN KEY (evento_id) REFERENCES eventos_graduacao(id),
    CONSTRAINT fk_convites_graduacao_aluno FOREIGN KEY (aluno_id) REFERENCES alunos(id),
    CONSTRAINT fk_convites_graduacao_atual FOREIGN KEY (graduacao_atual_id) REFERENCES graduacoes(id),
    CONSTRAINT fk_convites_graduacao_destino FOREIGN KEY (graduacao_destino_id) REFERENCES graduacoes(id),
    CONSTRAINT fk_convites_graduacao_usuario FOREIGN KEY (enviado_por_id) REFERENCES usuarios(id),
    CONSTRAINT uk_convite_graduacao UNIQUE (evento_id, aluno_id, graduacao_destino_id)
);

CREATE INDEX IF NOT EXISTS idx_convites_graduacao_academia ON convites_graduacao (academia_id);
CREATE INDEX IF NOT EXISTS idx_convites_graduacao_evento ON convites_graduacao (evento_id);
CREATE INDEX IF NOT EXISTS idx_convites_graduacao_aluno ON convites_graduacao (aluno_id);
CREATE INDEX IF NOT EXISTS idx_convites_graduacao_status ON convites_graduacao (academia_id, status);

CREATE TABLE IF NOT EXISTS inscricoes_graduacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id BIGINT NOT NULL,
    evento_id BIGINT NOT NULL,
    aluno_id BIGINT NOT NULL,
    graduacao_destino_id BIGINT NOT NULL,
    convite_id BIGINT,
    valor NUMERIC(10, 2) NOT NULL,
    status VARCHAR(40) NOT NULL,
    inscrito_em TIMESTAMP NOT NULL,
    cancelado_em TIMESTAMP,
    observacao VARCHAR(500),
    chave_inscricao_ativa VARCHAR(80) UNIQUE,
    CONSTRAINT fk_inscricoes_graduacao_academia FOREIGN KEY (academia_id) REFERENCES academias(id),
    CONSTRAINT fk_inscricoes_graduacao_evento FOREIGN KEY (evento_id) REFERENCES eventos_graduacao(id),
    CONSTRAINT fk_inscricoes_graduacao_aluno FOREIGN KEY (aluno_id) REFERENCES alunos(id),
    CONSTRAINT fk_inscricoes_graduacao_destino FOREIGN KEY (graduacao_destino_id) REFERENCES graduacoes(id),
    CONSTRAINT fk_inscricoes_graduacao_convite FOREIGN KEY (convite_id) REFERENCES convites_graduacao(id)
);

CREATE INDEX IF NOT EXISTS idx_inscricoes_graduacao_academia ON inscricoes_graduacao (academia_id);
CREATE INDEX IF NOT EXISTS idx_inscricoes_graduacao_evento ON inscricoes_graduacao (evento_id);
CREATE INDEX IF NOT EXISTS idx_inscricoes_graduacao_aluno ON inscricoes_graduacao (aluno_id);
CREATE INDEX IF NOT EXISTS idx_inscricoes_graduacao_status ON inscricoes_graduacao (academia_id, status);
