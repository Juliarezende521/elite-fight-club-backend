CREATE TABLE IF NOT EXISTS avaliacoes_graduacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id BIGINT NOT NULL,
    inscricao_id BIGINT NOT NULL,
    evento_id BIGINT NOT NULL,
    aluno_id BIGINT NOT NULL,
    graduacao_atual_id BIGINT NOT NULL,
    graduacao_destino_id BIGINT NOT NULL,
    status_presenca VARCHAR(30) NOT NULL,
    resultado VARCHAR(30) NOT NULL,
    observacao_tecnica VARCHAR(2000),
    nota_tecnica NUMERIC(4, 2),
    avaliado_em TIMESTAMP,
    avaliado_por_id BIGINT,
    promocao_confirmada BOOLEAN NOT NULL DEFAULT FALSE,
    promovido_em TIMESTAMP,
    promovido_por_id BIGINT,
    historico_gerado_id BIGINT,
    historico_gerado_flag BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP NOT NULL,
    presenca_registrada_em TIMESTAMP,
    presenca_registrada_por_id BIGINT,
    status_presenca_anterior VARCHAR(30),
    status_presenca_atual VARCHAR(30),
    observacao_presenca VARCHAR(500),
    resultado_anterior VARCHAR(30),
    resultado_atual VARCHAR(30),
    observacao_promocao VARCHAR(1000),
    CONSTRAINT uk_avaliacao_graduacao_inscricao UNIQUE (inscricao_id),
    CONSTRAINT fk_avaliacoes_graduacao_academia FOREIGN KEY (academia_id) REFERENCES academias(id),
    CONSTRAINT fk_avaliacoes_graduacao_inscricao FOREIGN KEY (inscricao_id) REFERENCES inscricoes_graduacao(id),
    CONSTRAINT fk_avaliacoes_graduacao_evento FOREIGN KEY (evento_id) REFERENCES eventos_graduacao(id),
    CONSTRAINT fk_avaliacoes_graduacao_aluno FOREIGN KEY (aluno_id) REFERENCES alunos(id),
    CONSTRAINT fk_avaliacoes_graduacao_atual FOREIGN KEY (graduacao_atual_id) REFERENCES graduacoes(id),
    CONSTRAINT fk_avaliacoes_graduacao_destino FOREIGN KEY (graduacao_destino_id) REFERENCES graduacoes(id),
    CONSTRAINT fk_avaliacoes_graduacao_avaliador FOREIGN KEY (avaliado_por_id) REFERENCES usuarios(id),
    CONSTRAINT fk_avaliacoes_graduacao_promotor FOREIGN KEY (promovido_por_id) REFERENCES usuarios(id),
    CONSTRAINT fk_avaliacoes_graduacao_historico FOREIGN KEY (historico_gerado_id) REFERENCES historico_graduacoes(id),
    CONSTRAINT fk_avaliacoes_graduacao_presenca_usuario FOREIGN KEY (presenca_registrada_por_id) REFERENCES usuarios(id),
    CONSTRAINT ck_avaliacoes_graduacao_nota CHECK (nota_tecnica IS NULL OR (nota_tecnica >= 0 AND nota_tecnica <= 10))
);

CREATE INDEX IF NOT EXISTS idx_avaliacoes_graduacao_academia
    ON avaliacoes_graduacao (academia_id);

CREATE INDEX IF NOT EXISTS idx_avaliacoes_graduacao_evento
    ON avaliacoes_graduacao (academia_id, evento_id);

CREATE INDEX IF NOT EXISTS idx_avaliacoes_graduacao_aluno
    ON avaliacoes_graduacao (academia_id, aluno_id);

CREATE INDEX IF NOT EXISTS idx_avaliacoes_graduacao_presenca
    ON avaliacoes_graduacao (academia_id, evento_id, status_presenca);

CREATE INDEX IF NOT EXISTS idx_avaliacoes_graduacao_resultado
    ON avaliacoes_graduacao (academia_id, evento_id, resultado);
