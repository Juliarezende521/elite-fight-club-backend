CREATE TABLE IF NOT EXISTS historico_graduacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id BIGINT NOT NULL,
    aluno_id BIGINT NOT NULL,
    graduacao_anterior_id BIGINT,
    nova_graduacao_id BIGINT NOT NULL,
    alterado_em TIMESTAMP NOT NULL,
    alterado_por_id BIGINT NOT NULL,
    motivo VARCHAR(50) NOT NULL,
    observacao VARCHAR(500),
    promocao_por_avaliacao BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_historico_graduacoes_academia FOREIGN KEY (academia_id) REFERENCES academias(id),
    CONSTRAINT fk_historico_graduacoes_aluno FOREIGN KEY (aluno_id) REFERENCES alunos(id),
    CONSTRAINT fk_historico_graduacoes_anterior FOREIGN KEY (graduacao_anterior_id) REFERENCES graduacoes(id),
    CONSTRAINT fk_historico_graduacoes_nova FOREIGN KEY (nova_graduacao_id) REFERENCES graduacoes(id),
    CONSTRAINT fk_historico_graduacoes_usuario FOREIGN KEY (alterado_por_id) REFERENCES usuarios(id)
);

CREATE INDEX IF NOT EXISTS idx_historico_graduacoes_academia
    ON historico_graduacoes (academia_id);

CREATE INDEX IF NOT EXISTS idx_historico_graduacoes_aluno
    ON historico_graduacoes (aluno_id);

CREATE INDEX IF NOT EXISTS idx_historico_graduacoes_aluno_data
    ON historico_graduacoes (aluno_id, alterado_em DESC);

INSERT INTO historico_graduacoes (
    academia_id,
    aluno_id,
    graduacao_anterior_id,
    nova_graduacao_id,
    alterado_em,
    alterado_por_id,
    motivo,
    observacao,
    promocao_por_avaliacao
)
SELECT
    a.academia_id,
    a.id,
    NULL,
    a.graduacao_id,
    NOW(),
    u.id,
    'CADASTRO_INICIAL',
    'Registro inicial criado pela migração V11 para preservar histórico de alunos existentes.',
    FALSE
FROM alunos a
JOIN usuarios u ON u.academia_id = a.academia_id
WHERE a.graduacao_id IS NOT NULL
  AND NOT EXISTS (
      SELECT 1
      FROM historico_graduacoes h
      WHERE h.academia_id = a.academia_id
        AND h.aluno_id = a.id
  )
  AND u.id = (
      SELECT u2.id
      FROM usuarios u2
      WHERE u2.academia_id = a.academia_id
      ORDER BY
          CASE u2.perfil
              WHEN 'ADMIN' THEN 1
              WHEN 'PROFESSOR' THEN 2
              ELSE 3
          END,
          u2.id
      LIMIT 1
  );
