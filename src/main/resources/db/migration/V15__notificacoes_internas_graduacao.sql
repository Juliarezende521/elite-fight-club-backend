CREATE TABLE IF NOT EXISTS notificacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id BIGINT,
    destinatario_id BIGINT,
    tipo_notificacao VARCHAR(80) NOT NULL,
    titulo VARCHAR(180),
    mensagem VARCHAR(2000) NOT NULL,
    data_envio TIMESTAMP NOT NULL,
    enviada BOOLEAN NOT NULL DEFAULT FALSE,
    lida BOOLEAN NOT NULL DEFAULT FALSE,
    criada_em TIMESTAMP,
    lida_em TIMESTAMP,
    referencia_tipo VARCHAR(80),
    referencia_id BIGINT,
    chave_idempotencia VARCHAR(220),
    agendada_para TIMESTAMP,
    status VARCHAR(30),
    motivo_falha VARCHAR(1000),
    aluno_id BIGINT,
    financeiro_id BIGINT,
    CONSTRAINT fk_notificacoes_academia FOREIGN KEY (academia_id) REFERENCES academias(id),
    CONSTRAINT fk_notificacoes_destinatario FOREIGN KEY (destinatario_id) REFERENCES usuarios(id),
    CONSTRAINT fk_notificacoes_aluno FOREIGN KEY (aluno_id) REFERENCES alunos(id),
    CONSTRAINT fk_notificacoes_financeiro FOREIGN KEY (financeiro_id) REFERENCES financeiro(id)
);

