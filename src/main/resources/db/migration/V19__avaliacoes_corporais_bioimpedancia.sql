CREATE TABLE IF NOT EXISTS avaliacoes_corporais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id BIGINT NOT NULL,
    aluno_id BIGINT NOT NULL,
    data_avaliacao DATE NOT NULL,
    altura_metros NUMERIC(5, 2),
    peso_registrado NUMERIC(6, 2),
    observacao VARCHAR(2000),
    criada_em TIMESTAMP NOT NULL,
    atualizada_em TIMESTAMP,
    criada_por_id BIGINT NOT NULL,
    atualizada_por_id BIGINT,
    ativa BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_avaliacoes_corporais_academia FOREIGN KEY (academia_id) REFERENCES academias(id),
    CONSTRAINT fk_avaliacoes_corporais_aluno FOREIGN KEY (aluno_id) REFERENCES alunos(id),
    CONSTRAINT fk_avaliacoes_corporais_criada_por FOREIGN KEY (criada_por_id) REFERENCES usuarios(id),
    CONSTRAINT fk_avaliacoes_corporais_atualizada_por FOREIGN KEY (atualizada_por_id) REFERENCES usuarios(id),
    CONSTRAINT ck_avaliacoes_corporais_altura CHECK (altura_metros IS NULL OR (altura_metros > 0 AND altura_metros <= 3)),
    CONSTRAINT ck_avaliacoes_corporais_peso CHECK (peso_registrado IS NULL OR (peso_registrado > 0 AND peso_registrado <= 500))
);

CREATE INDEX IF NOT EXISTS idx_avaliacoes_corporais_academia_aluno_data
    ON avaliacoes_corporais (academia_id, aluno_id, data_avaliacao);

CREATE INDEX IF NOT EXISTS idx_avaliacoes_corporais_aluno_ativa
    ON avaliacoes_corporais (aluno_id, ativa);

CREATE UNIQUE INDEX IF NOT EXISTS uk_avaliacoes_corporais_aluno_data_ativa
    ON avaliacoes_corporais (academia_id, aluno_id, data_avaliacao, ativa);

CREATE TABLE IF NOT EXISTS medidas_corporais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    avaliacao_id BIGINT NOT NULL UNIQUE,
    pescoco NUMERIC(6, 2),
    ombros NUMERIC(6, 2),
    torax NUMERIC(6, 2),
    cintura NUMERIC(6, 2),
    abdomen NUMERIC(6, 2),
    quadril NUMERIC(6, 2),
    braco_direito NUMERIC(6, 2),
    braco_esquerdo NUMERIC(6, 2),
    antebraco_direito NUMERIC(6, 2),
    antebraco_esquerdo NUMERIC(6, 2),
    coxa_direita NUMERIC(6, 2),
    coxa_esquerda NUMERIC(6, 2),
    panturrilha_direita NUMERIC(6, 2),
    panturrilha_esquerda NUMERIC(6, 2),
    CONSTRAINT fk_medidas_corporais_avaliacao FOREIGN KEY (avaliacao_id) REFERENCES avaliacoes_corporais(id),
    CONSTRAINT ck_medidas_corporais_valores CHECK (
        (pescoco IS NULL OR (pescoco > 0 AND pescoco <= 300)) AND
        (ombros IS NULL OR (ombros > 0 AND ombros <= 300)) AND
        (torax IS NULL OR (torax > 0 AND torax <= 300)) AND
        (cintura IS NULL OR (cintura > 0 AND cintura <= 300)) AND
        (abdomen IS NULL OR (abdomen > 0 AND abdomen <= 300)) AND
        (quadril IS NULL OR (quadril > 0 AND quadril <= 300)) AND
        (braco_direito IS NULL OR (braco_direito > 0 AND braco_direito <= 300)) AND
        (braco_esquerdo IS NULL OR (braco_esquerdo > 0 AND braco_esquerdo <= 300)) AND
        (antebraco_direito IS NULL OR (antebraco_direito > 0 AND antebraco_direito <= 300)) AND
        (antebraco_esquerdo IS NULL OR (antebraco_esquerdo > 0 AND antebraco_esquerdo <= 300)) AND
        (coxa_direita IS NULL OR (coxa_direita > 0 AND coxa_direita <= 300)) AND
        (coxa_esquerda IS NULL OR (coxa_esquerda > 0 AND coxa_esquerda <= 300)) AND
        (panturrilha_direita IS NULL OR (panturrilha_direita > 0 AND panturrilha_direita <= 300)) AND
        (panturrilha_esquerda IS NULL OR (panturrilha_esquerda > 0 AND panturrilha_esquerda <= 300))
    )
);

CREATE TABLE IF NOT EXISTS bioimpedancias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    avaliacao_id BIGINT NOT NULL UNIQUE,
    percentual_gordura NUMERIC(5, 2),
    massa_gorda_kg NUMERIC(6, 2),
    massa_magra_kg NUMERIC(6, 2),
    massa_muscular_kg NUMERIC(6, 2),
    agua_corporal_percentual NUMERIC(5, 2),
    gordura_visceral NUMERIC(6, 2),
    massa_ossea_kg NUMERIC(6, 2),
    metabolismo_basal_kcal NUMERIC(8, 2),
    idade_metabolica NUMERIC(6, 2),
    CONSTRAINT fk_bioimpedancias_avaliacao FOREIGN KEY (avaliacao_id) REFERENCES avaliacoes_corporais(id),
    CONSTRAINT ck_bioimpedancias_valores CHECK (
        (percentual_gordura IS NULL OR (percentual_gordura >= 0 AND percentual_gordura <= 100)) AND
        (agua_corporal_percentual IS NULL OR (agua_corporal_percentual >= 0 AND agua_corporal_percentual <= 100)) AND
        (massa_gorda_kg IS NULL OR massa_gorda_kg >= 0) AND
        (massa_magra_kg IS NULL OR massa_magra_kg >= 0) AND
        (massa_muscular_kg IS NULL OR massa_muscular_kg >= 0) AND
        (gordura_visceral IS NULL OR gordura_visceral >= 0) AND
        (massa_ossea_kg IS NULL OR massa_ossea_kg >= 0) AND
        (metabolismo_basal_kcal IS NULL OR metabolismo_basal_kcal >= 0) AND
        (idade_metabolica IS NULL OR idade_metabolica >= 0)
    )
);
