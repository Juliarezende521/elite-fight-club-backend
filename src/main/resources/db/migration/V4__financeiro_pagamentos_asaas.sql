        ALTER TABLE pagamentos ADD COLUMN IF NOT EXISTS pix_qr_code_base64 TEXT;
        ALTER TABLE pagamentos ADD COLUMN IF NOT EXISTS data_expiracao TIMESTAMP;
        ALTER TABLE pagamentos ADD COLUMN IF NOT EXISTS ultimo_evento_externo VARCHAR(120);
        ALTER TABLE pagamentos ADD COLUMN IF NOT EXISTS ultimo_evento_em TIMESTAMP;
        ALTER TABLE pagamentos ADD COLUMN IF NOT EXISTS observacao VARCHAR(255);
        ALTER TABLE pagamentos ADD COLUMN IF NOT EXISTS confirmado_por_usuario_id BIGINT;
        ALTER TABLE pagamentos ADD COLUMN IF NOT EXISTS conciliado_em TIMESTAMP;
        CREATE INDEX IF NOT EXISTS idx_pagamento_externo ON pagamentos (id_pagamento_externo);

        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_pagamentos_confirmado_por') THEN
            ALTER TABLE pagamentos ADD CONSTRAINT fk_pagamentos_confirmado_por FOREIGN KEY (confirmado_por_usuario_id) REFERENCES usuarios(id);
        END IF;
    END IF;

    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = 'faturas') THEN
        CREATE UNIQUE INDEX IF NOT EXISTS uk_fatura_academia_aluno_mes_idx ON faturas (academia_id, aluno_id, mes_referencia);
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS eventos_pagamento_externo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provedor VARCHAR(40) NOT NULL,
    evento_externo_id VARCHAR(120) NOT NULL,
    tipo_evento VARCHAR(80) NOT NULL,
    pagamento_externo_id VARCHAR(120),
    pagamento_id BIGINT,
    processado_em TIMESTAMP NOT NULL,
    CONSTRAINT uk_evento_pagamento_externo UNIQUE (provedor, evento_externo_id, tipo_evento)
);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = 'pagamentos') THEN
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_evento_pagamento_pagamento') THEN
            ALTER TABLE eventos_pagamento_externo ADD CONSTRAINT fk_evento_pagamento_pagamento FOREIGN KEY (pagamento_id) REFERENCES pagamentos(id);
        END IF;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_eventos_pagamento_externo_pagamento ON eventos_pagamento_externo (pagamento_id);
