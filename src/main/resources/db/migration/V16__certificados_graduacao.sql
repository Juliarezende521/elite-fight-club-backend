CREATE TABLE IF NOT EXISTS certificados_graduacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id BIGINT NOT NULL,
    aluno_id BIGINT NOT NULL,
    evento_id BIGINT NOT NULL,
    graduacao_anterior_id BIGINT,
    graduacao_nova_id BIGINT NOT NULL,
    avaliacao_id BIGINT NOT NULL,
    historico_id BIGINT NOT NULL,
    numero_certificado VARCHAR(30) NOT NULL,
    codigo_validacao VARCHAR(30) NOT NULL,
    data_emissao TIMESTAMP NOT NULL,
    emitido_por_id BIGINT NOT NULL,
    observacoes VARCHAR(1000),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    motivo_cancelamento VARCHAR(1000),
    cancelado_em TIMESTAMP,
    cancelado_por_id BIGINT,
    CONSTRAINT uk_certificado_graduacao_numero UNIQUE (numero_certificado),
    CONSTRAINT uk_certificado_graduacao_codigo UNIQUE (codigo_validacao),
    CONSTRAINT uk_certificado_graduacao_avaliacao UNIQUE (avaliacao_id),
    CONSTRAINT fk_certificados_graduacao_academia FOREIGN KEY (academia_id) REFERENCES academias(id),
    CONSTRAINT fk_certificados_graduacao_aluno FOREIGN KEY (aluno_id) REFERENCES alunos(id),
    CONSTRAINT fk_certificados_graduacao_evento FOREIGN KEY (evento_id) REFERENCES eventos_graduacao(id),
    CONSTRAINT fk_certificados_graduacao_anterior FOREIGN KEY (graduacao_anterior_id) REFERENCES graduacoes(id),
    CONSTRAINT fk_certificados_graduacao_nova FOREIGN KEY (graduacao_nova_id) REFERENCES graduacoes(id),
    CONSTRAINT fk_certificados_graduacao_avaliacao FOREIGN KEY (avaliacao_id) REFERENCES avaliacoes_graduacao(id),
    CONSTRAINT fk_certificados_graduacao_historico FOREIGN KEY (historico_id) REFERENCES historico_graduacoes(id),
    CONSTRAINT fk_certificados_graduacao_emitido_por FOREIGN KEY (emitido_por_id) REFERENCES usuarios(id),
    CONSTRAINT fk_certificados_graduacao_cancelado_por FOREIGN KEY (cancelado_por_id) REFERENCES usuarios(id)
);

CREATE INDEX IF NOT EXISTS idx_certificados_graduacao_academia
    ON certificados_graduacao (academia_id, data_emissao);

CREATE INDEX IF NOT EXISTS idx_certificados_graduacao_aluno
    ON certificados_graduacao (academia_id, aluno_id, data_emissao);

CREATE INDEX IF NOT EXISTS idx_certificados_graduacao_evento
    ON certificados_graduacao (academia_id, evento_id);

CREATE INDEX IF NOT EXISTS idx_certificados_graduacao_ativo
    ON certificados_graduacao (academia_id, ativo);
