CREATE TABLE IF NOT EXISTS metas_peso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id BIGINT NOT NULL,
    aluno_id BIGINT NOT NULL,
    peso_inicial NUMERIC(6, 2) NOT NULL,
    peso_alvo NUMERIC(6, 2) NOT NULL,
    peso_inicial_manual BOOLEAN NOT NULL DEFAULT FALSE,
    data_inicio DATE NOT NULL,
    data_limite DATE,
    status VARCHAR(30) NOT NULL,
    observacao VARCHAR(1000),
    criada_em TIMESTAMP NOT NULL,
    atualizada_em TIMESTAMP,
    encerrada_em TIMESTAMP,
    criada_por_id BIGINT NOT NULL,
    atualizada_por_id BIGINT,
    encerrada_por_id BIGINT,
    CONSTRAINT fk_metas_peso_academia FOREIGN KEY (academia_id) REFERENCES academias(id),
    CONSTRAINT fk_metas_peso_aluno FOREIGN KEY (aluno_id) REFERENCES alunos(id),
    CONSTRAINT fk_metas_peso_criada_por FOREIGN KEY (criada_por_id) REFERENCES usuarios(id),
    CONSTRAINT fk_metas_peso_atualizada_por FOREIGN KEY (atualizada_por_id) REFERENCES usuarios(id),
    CONSTRAINT fk_metas_peso_encerrada_por FOREIGN KEY (encerrada_por_id) REFERENCES usuarios(id),
    CONSTRAINT ck_metas_peso_valores CHECK (peso_inicial > 0 AND peso_inicial <= 500 AND peso_alvo > 0 AND peso_alvo <= 500),
    CONSTRAINT ck_metas_peso_alvo_diferente CHECK (peso_inicial <> peso_alvo),
    CONSTRAINT ck_metas_peso_datas CHECK (data_limite IS NULL OR data_limite > data_inicio)
);

CREATE INDEX IF NOT EXISTS idx_metas_peso_academia_aluno_status
    ON metas_peso (academia_id, aluno_id, status);

CREATE INDEX IF NOT EXISTS idx_metas_peso_aluno_data
    ON metas_peso (aluno_id, data_inicio);
