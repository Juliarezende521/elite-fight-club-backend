CREATE TABLE IF NOT EXISTS evolucao_peso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id BIGINT NOT NULL,
    aluno_id BIGINT NOT NULL,
    peso NUMERIC(6, 2) NOT NULL,
    data_registro DATE NOT NULL,
    observacao VARCHAR(1000),
    criado_em TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP,
    criado_por_id BIGINT NOT NULL,
    atualizado_por_id BIGINT,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_evolucao_peso_academia FOREIGN KEY (academia_id) REFERENCES academias(id),
    CONSTRAINT fk_evolucao_peso_aluno FOREIGN KEY (aluno_id) REFERENCES alunos(id),
    CONSTRAINT fk_evolucao_peso_criado_por FOREIGN KEY (criado_por_id) REFERENCES usuarios(id),
    CONSTRAINT fk_evolucao_peso_atualizado_por FOREIGN KEY (atualizado_por_id) REFERENCES usuarios(id),
    CONSTRAINT ck_evolucao_peso_valor CHECK (peso > 0 AND peso <= 500)
);

CREATE INDEX IF NOT EXISTS idx_evolucao_peso_academia_aluno_data
    ON evolucao_peso (academia_id, aluno_id, data_registro);

CREATE INDEX IF NOT EXISTS idx_evolucao_peso_aluno_ativo
    ON evolucao_peso (aluno_id, ativo);

CREATE UNIQUE INDEX IF NOT EXISTS uk_evolucao_peso_aluno_data_ativo
    ON evolucao_peso (academia_id, aluno_id, data_registro, ativo);
