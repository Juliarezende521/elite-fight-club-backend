CREATE TABLE IF NOT EXISTS aulas_turma (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id BIGINT NOT NULL,
    horario_turma_id BIGINT NOT NULL,
    professor_id BIGINT NOT NULL,
    modalidade_id BIGINT NOT NULL,
    data DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fim TIME NOT NULL,
    capacidade_maxima INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL,
    observacao VARCHAR(500),
    criado_em TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP NOT NULL,
    aula_original_id BIGINT,
    CONSTRAINT uk_aula_turma_horario_data UNIQUE (horario_turma_id, data)
);

CREATE TABLE IF NOT EXISTS aulas_personal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id BIGINT NOT NULL,
    agenda_personal_id BIGINT NOT NULL,
    aluno_id BIGINT NOT NULL,
    professor_id BIGINT NOT NULL,
    data DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fim TIME NOT NULL,
    status VARCHAR(30) NOT NULL,
    observacao VARCHAR(500),
    criado_em TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP NOT NULL,
    aula_original_id BIGINT,
    CONSTRAINT uk_aula_personal_agenda_data UNIQUE (agenda_personal_id, data)
);

CREATE INDEX IF NOT EXISTS idx_aulas_turma_professor_data ON aulas_turma (academia_id, professor_id, data);
CREATE INDEX IF NOT EXISTS idx_aulas_personal_professor_data ON aulas_personal (academia_id, professor_id, data);
CREATE INDEX IF NOT EXISTS idx_aulas_turma_data ON aulas_turma (academia_id, data);
CREATE INDEX IF NOT EXISTS idx_aulas_personal_data ON aulas_personal (academia_id, data);

